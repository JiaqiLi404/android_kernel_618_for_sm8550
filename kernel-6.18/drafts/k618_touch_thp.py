def main(argv):
    root = argv[1]
    done = 0
    for rel, old, new in EDITS:
        path = os.path.join(root, rel)
        text = open(path, encoding="utf-8", errors="surrogateescape").read()
        if new in text and (old not in text or old in new):
            continue
        if old not in text:
            print(f"k618_touch_thp: {rel}: text to change not found:\n{old[:200]}", file=sys.stderr)
            return 1
        if text.count(old) != 1:
            print(f"k618_touch_thp: {rel}: text to change found {text.count(old)} times", file=sys.stderr)
            return 1
        open(path, "w", encoding="utf-8", errors="surrogateescape", newline="").write(text.replace(old, new))
        done += 1
    print(f"k618_touch_thp: {done} of {len(EDITS)} edits applied")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
